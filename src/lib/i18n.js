export const LANGUAGES = [
  { code: 'en', locale: 'en-IN', name: 'English', native: 'English' },
  { code: 'hi', locale: 'hi-IN', name: 'Hindi', native: 'हिन्दी' },
  { code: 'te', locale: 'te-IN', name: 'Telugu', native: 'తెలుగు' },
  { code: 'ta', locale: 'ta-IN', name: 'Tamil', native: 'தமிழ்' },
];

export const LANG_CODES = LANGUAGES.map((l) => l.code);
const STORAGE_KEY = 'mindmate-lang';

let activeLang = 'en';

export function getLanguageMeta(code = activeLang) {
  return LANGUAGES.find((l) => l.code === code) || LANGUAGES[0];
}

export function getActiveLanguage() {
  return activeLang;
}

export function getSpeechLocale(code = activeLang) {
  return getLanguageMeta(code).locale;
}

export function readStoredLanguage() {
  if (typeof window === 'undefined') return 'en';
  const stored = window.localStorage.getItem(STORAGE_KEY);
  return LANG_CODES.includes(stored) ? stored : 'en';
}

export function setActiveLanguage(code) {
  const next = LANG_CODES.includes(code) ? code : 'en';
  activeLang = next;
  if (typeof window !== 'undefined') {
    window.localStorage.setItem(STORAGE_KEY, next);
    document.documentElement.lang = getSpeechLocale(next);
  }
  return next;
}

export function t(key, vars = {}, lang = activeLang) {
  const table = STRINGS[lang] || STRINGS.en;
  let text = table[key] ?? STRINGS.en[key] ?? key;
  Object.entries(vars).forEach(([name, value]) => {
    text = text.replaceAll(`{${name}}`, String(value ?? ''));
  });
  return text;
}

export function greetingKey() {
  const hour = new Date().getHours();
  if (hour < 12) return 'greet.morning';
  if (hour < 17) return 'greet.afternoon';
  return 'greet.evening';
}

export function gameTitleKey(gameId) {
  if (gameId === 'memory-match') return 'game.memoryMatch';
  if (gameId === 'pattern-recall') return 'game.patternRecall';
  if (gameId === 'object-recognition') return 'game.objectRecognition';
  return 'game.memoryMatch';
}

export function gameDescKey(gameId) {
  if (gameId === 'memory-match') return 'game.memoryDesc';
  if (gameId === 'pattern-recall') return 'game.patternDesc';
  if (gameId === 'object-recognition') return 'game.objectDesc';
  return 'game.memoryDesc';
}

export function difficultyKey(tierOrLabel) {
  const v = String(tierOrLabel || '').toLowerCase();
  if (v === 'easy') return 'game.easy';
  if (v === 'hard' || v === 'challenge') return 'game.challenge';
  return 'game.medium';
}

